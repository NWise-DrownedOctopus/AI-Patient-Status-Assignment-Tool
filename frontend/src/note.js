// Chart-note generator. Pure JavaScript (no Vue), so the wording rules can be tested in Node.
//
// Wording follows the hospital guide, because payers react to it:
//   - Inpatient:  "Admit to inpatient for monitoring and/or treatment of ..."
//   - Observation is a noun: "Place the patient in observation ..."
//   - Never "admit to observation", and never "observe" a patient overnight.
// Needs-review results get no note: there is no recommendation to document yet.

export const INPATIENT_PHRASE = 'Admit to inpatient for monitoring and/or treatment of';
export const OBSERVATION_PHRASE = 'Place the patient in observation for';

const FOOTER =
  'Recommendation generated by a decision-support tool using the hospital\'s Level of Care guide. ' +
  'The final level-of-care decision rests on physician judgment.';

const bullets = (items) => items.map((t) => `- ${t}`);

/**
 * @param {object} result  output of evaluate() (after applyPayer)
 * @param {object} rule    the condition file, for its name
 * @returns {string|null}  note text, or null when there is nothing to document yet
 */
export function buildNote(result, rule) {
  if (!result || (result.status !== 'inpatient' && result.status !== 'observation')) return null;

  const name = rule?.noteName ?? (rule?.label ?? result.label ?? 'this condition').toLowerCase();
  const lines = [];

  if (result.status === 'inpatient') {
    lines.push(`Level of care: ${INPATIENT_PHRASE} ${name}.`);
    const findings = [...result.matched.map((m) => m.text), ...(result.medicare?.lines ?? [])];
    if (findings.length) lines.push('', 'Supporting findings:', ...bullets(findings));
  } else {
    lines.push(`Level of care: ${OBSERVATION_PHRASE} ${name}.`);
    lines.push('Inpatient criteria in the hospital guide were not met.');
    if (result.supports?.length) {
      lines.push('', 'Findings consistent with observation:', ...bullets(result.supports.map((s) => s.text)));
    }
    if (result.notMet?.length) {
      lines.push('', 'Findings reviewed:', ...bullets(result.notMet.map((s) => s.text)));
    }
  }

  lines.push('', FOOTER);
  return lines.join('\n');
}
